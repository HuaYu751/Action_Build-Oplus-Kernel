#!/bin/bash
# p5_gen_hidden_syms.sh — 任务书 9-B / B1：从 vmlinux 生成隐藏符号表头文件
# 用法: p5_gen_hidden_syms.sh <vmlinux路径> <输出头文件路径>
# 在 kernel 源码树根目录（common/）下执行。
set -e

VMLINUX="${1:?usage: $0 <vmlinux> <output_header>}"
OUT="${2:?usage: $0 <vmlinux> <output_header>}"

[ -f "$VMLINUX" ] || { echo "【P5】vmlinux 不存在: $VMLINUX"; exit 1; }

# 需隐藏的符号前缀（宽松正则，覆盖编译器 .constprop.0 等后缀变体）：
#   nm_* / nomount_*        —— NoMount 引擎（P2 内置时存在；钩子函数是 nomount_ 前缀）
#   oplus_dfr_* / dispatch_* —— 我们的驱动（P3 内置时存在）
#   readwrite_process*       —— 旧版驱动命名（防御性保留）
# __kcfi_typeid_* 是 CFI 生成的类型 id，原厂也有大量此类符号，
# 只过滤我们前缀命中的（正则已含前缀，天然只命中我们的）。
nm "$VMLINUX" 2>/dev/null | awk '{print $3}' | \
  grep -E '^(nm_|nomount_|vfs_map_|oplus_dfr_|dispatch_|readwrite_process)' | \
  sort -u > /tmp/hidden_syms.txt

COUNT=$(wc -l < /tmp/hidden_syms.txt)
echo "【P5】过滤表共 $COUNT 个符号："
cat /tmp/hidden_syms.txt

if [ "$COUNT" -eq 0 ]; then
  echo "【P5】过滤表为空（P2/P3 未内置时属正常，跳过过滤）"
  exit 2
fi
if [ "$COUNT" -ge 500 ]; then
  echo "【P5】过滤表异常大（>=500），正则有误伤风险，中止"
  exit 1
fi

mkdir -p "$(dirname "$OUT")"
{
  echo '/* auto-generated by p5_gen_hidden_syms.sh - do not edit */'
  echo '#ifndef HIDDEN_SYMS_H'
  echo '#define HIDDEN_SYMS_H'
  echo '#include <linux/string.h>'
  echo 'static const char *const hidden_syms[] = {'
  sed 's/.*/\t"&",/' /tmp/hidden_syms.txt
  echo '};'
  echo '#define HIDDEN_SYMS_COUNT (sizeof(hidden_syms) / sizeof(hidden_syms[0]))'
  echo 'static inline int kallsyms_is_hidden(const char *name)'
  echo '{'
  echo '	int lo = 0, hi = (int)HIDDEN_SYMS_COUNT - 1, mid, r;'
  echo ''
  echo '	while (lo <= hi) {'
  echo '		mid = (lo + hi) / 2;'
  echo '		r = strcmp(name, hidden_syms[mid]);'
  echo '		if (r == 0)'
  echo '			return 1;'
  echo '		if (r < 0)'
  echo '			hi = mid - 1;'
  echo '		else'
  echo '			lo = mid + 1;'
  echo '	}'
  echo '	return 0;'
  echo '}'
  echo '#endif'
} > "$OUT"

echo "【P5】已生成 $OUT（$COUNT 个符号）"
